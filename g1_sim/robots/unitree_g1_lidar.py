def mid360_cfg(
    robot_prim_path: str,
    mesh_prim_paths: list[str] | None = None,
    samples: int = 20000,
    update_frequency: float = 10.0,
    max_distance: float = 40.0,
    debug_vis: bool = False,
) -> LidarSensorCfg:
    """Livox Mid-360 attached to the G1's torso.

    Args:
        robot_prim_path: prim path of the robot, e.g. ``"{ENV_REGEX_NS}/Robot"``.
        mesh_prim_paths: what the rays may hit. Defaults to ``["/World/ground"]``.
        samples: rays per scan. **Do not lower this to save time** - the loader
            takes a contiguous slice of a time-ordered scan trajectory, so a
            smaller value narrows the elevation coverage rather than thinning
            it. Below ~20000 the pattern loses its downward rays entirely and
            the ground becomes invisible. Use the sensor's ``downsample``
            option instead.
        update_frequency: scan rate in Hz; 10 Hz matches the real device.
        max_distance: maximum range in metres.
        debug_vis: draw rays in the viewer.
    """
    if samples < 20000:
        raise ValueError(
            f"samples={samples} is below the Mid-360's native 20000. Because the "
            "scan pattern is sliced in time order, this silently removes all "
            "downward rays. Use downsample to reduce ray count instead."
        )

    return LidarSensorCfg(
        prim_path=f"{robot_prim_path}/{MID360_PARENT}",
        offset=LidarSensorCfg.OffsetCfg(pos=MID360_POS, rot=MID360_QUAT),
        pattern_cfg=LivoxPatternCfg(sensor_type="mid360", samples=samples),
        mesh_prim_paths=mesh_prim_paths if mesh_prim_paths is not None else ["/World/ground"],
        max_distance=max_distance,
        min_range=0.1,
        return_pointcloud=True,
        # Sensor-frame points: TF places them in the world, which keeps the
        # published cloud correct even while the robot moves.
        pointcloud_in_world_frame=False,
        update_frequency=update_frequency,
        debug_vis=debug_vis,
    )


def camera_cfg(
    robot_prim_path: str,
    width: int = 640,
    height: int = 480,
    update_period: float = 0.1,
) -> CameraCfg:
    """RealSense D435-style RGB-D camera on the G1's torso.

    Resolution defaults below the real D435's 1280x720: rendering dominates the
    frame budget on an 8 GB laptop GPU, and detection runs off the LiDAR anyway.
    """
    return CameraCfg(
        prim_path=f"{robot_prim_path}/{D435_PARENT}/d435_camera",
        offset=CameraCfg.OffsetCfg(pos=D435_POS, rot=D435_QUAT, convention="ros"),
        update_period=update_period,
        width=width,
        height=height,
        data_types=["rgb", "distance_to_image_plane"],
        spawn=sim_utils.PinholeCameraCfg(
            # ~69 deg horizontal FOV, matching the D435.
            focal_length=1.93,
            focus_distance=400.0,
            horizontal_aperture=2.682,
            clipping_range=(0.1, 20.0),
        ),
    )


def blind_radius(mount_height: float) -> float:
    """Radius of the Mid-360's blind cone at a given mount height, in metres."""
    return mount_height / math.tan(math.radians(MID360_MIN_TILT_DEG))


@configclass
class G1LidarSceneCfg:
    """Convenience bundle of the three configs for a standard single-robot scene."""

    robot: ArticulationCfg = G1_LIDAR_CFG.replace(prim_path="{ENV_REGEX_NS}/Robot")
    lidar: LidarSensorCfg = mid360_cfg("{ENV_REGEX_NS}/Robot")
    camera: CameraCfg = camera_cfg("{ENV_REGEX_NS}/Robot")
