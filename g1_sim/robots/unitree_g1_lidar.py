"""Unitree G1 with a Livox Mid-360 and a D435 camera, ready to drop into a scene.

Import the configs and add them to any ``InteractiveSceneCfg``:

    from g1_sim.robots.unitree_g1_lidar import G1_LIDAR_CFG, mid360_cfg, camera_cfg

    @configclass
    class MySceneCfg(InteractiveSceneCfg):
        robot  = G1_LIDAR_CFG.replace(prim_path="{ENV_REGEX_NS}/Robot")
        lidar  = mid360_cfg("{ENV_REGEX_NS}/Robot")
        camera = camera_cfg("{ENV_REGEX_NS}/Robot")

The USD is generated by ``scripts/convert_g1_urdf_to_usd.py`` and is imported
lazily, so this module can be read without a running simulator.
"""

from __future__ import annotations

import math
from pathlib import Path

import isaaclab.sim as sim_utils
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets import ArticulationCfg
from isaaclab.sensors import CameraCfg, LidarSensorCfg
from isaaclab.sensors.ray_caster.patterns import LivoxPatternCfg
from isaaclab.utils import configclass

G1_USD_PATH = str(Path(__file__).resolve().parents[2] / "assets/g1_29dof_sensors.usd")

# --------------------------------------------------------------------------
# Sensor mounts
#
# Both links already exist in g1_29dof.urdf as fixed children of torso_link;
# the conversion keeps them because merge_fixed_joints is disabled. The values
# below mirror the URDF so sensor offsets and published TF agree.
# --------------------------------------------------------------------------

MID360_PARENT = "torso_link"
# Per Unitree URDF: xyz=(0.0002835, 0.00003, 0.40618), rpy=(0, 0.0401, 0).
MID360_POS = (0.0002835, 0.00003, 0.40618)
# wxyz quaternion for rpy=(0, 0.0401, 0) — ~2.3° pitch about Y-axis, no roll.
import math as _math
_MID360_PITCH = 0.0401
MID360_QUAT = (
    _math.cos(_MID360_PITCH / 2),  # w
    0.0,                            # x (roll=0)
    _math.sin(_MID360_PITCH / 2),  # y (pitch)
    0.0,                            # z (yaw=0)
)

D435_PARENT = "torso_link"
D435_POS = (0.0576235, 0.01753, 0.41987)
# rpy = (0, 0.8307767, 0): pitched ~47.6 deg downward, so the camera covers the
# near ground that the LiDAR's -7.2 deg floor cannot reach.
_D435_PITCH = 0.8307767239493009
D435_QUAT = (math.cos(_D435_PITCH / 2), 0.0, math.sin(_D435_PITCH / 2), 0.0)

# Steepest downward ray in the Mid-360 pattern. There is no nadir ray, so the
# sensor is blind within roughly 8x its mount height - see Plan.md.
MID360_MIN_TILT_DEG = 7.16

JOINT_GROUPS = {
    "legs": [".*_hip_pitch_joint", ".*_hip_roll_joint", ".*_hip_yaw_joint", ".*_knee_joint"],
    "feet": [".*_ankle_pitch_joint", ".*_ankle_roll_joint"],
    "waist": ["waist_yaw_joint", "waist_roll_joint", "waist_pitch_joint"],
    "arms": [
        ".*_shoulder_pitch_joint",
        ".*_shoulder_roll_joint",
        ".*_shoulder_yaw_joint",
        ".*_elbow_joint",
        ".*_wrist_roll_joint",
        ".*_wrist_pitch_joint",
        ".*_wrist_yaw_joint",
    ],
}

# A stable, slightly crouched stance: knees and hips bent so the robot settles
# instead of buckling on the first physics step.
DEFAULT_JOINT_POS = {
    ".*_hip_pitch_joint": -0.20,
    ".*_knee_joint": 0.42,
    ".*_ankle_pitch_joint": -0.23,
    ".*_shoulder_pitch_joint": 0.35,
    ".*_elbow_joint": 0.87,
    "left_shoulder_roll_joint": 0.18,
    "right_shoulder_roll_joint": -0.18,
}

# Torso height in the default stance; the base spawns here so the feet start
# just above the ground rather than intersecting it.
DEFAULT_BASE_HEIGHT = 0.74


